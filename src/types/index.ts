/* Phase 13 — Smart Crop Recommendation                               */
/* ------------------------------------------------------------------ */

/**
 * Estimated suitability of a recommended crop. Advisory — never a guarantee
 * of yield or profit (the AI is instructed to keep this as an estimate).
 */
export type CropSuitability = "high" | "moderate" | "low";

/**
 * One recommended crop (Prompt 13). Mirrors the validated items returned by
 * the `recommend-crops` Edge Function and stored in the jsonb
 * `recommendations` column of `crop_recommendations`.
 */
export interface CropRecommendation {
  crop: string;
  suitability: CropSuitability;
  /** 0–100 AI self-assessed confidence, shown separately from suitability. */
  confidence: number;
  whySuitable: string;
  soilFit: string;
  waterRequirement: string;
  weatherFit: string;
  keyConsiderations: string[];
}

/**
 * A persisted recommended-crops run. Mirrors a `crop_recommendations` row
 * (mapped from snake_case columns). Every record is owned by a farm and was
 * produced by the real AI Edge Function from real farm context — never fake.
 */
export interface CropRecommendationRecord {
  id: string;
  farmId: string;
  recommendations: CropRecommendation[];
  summary: string;
  limitations: string[];
  needsMoreInformation: boolean;
  missingInformation: string[];
  createdAt: string;
}

/* ------------------------------------------------------------------ */
/* Phase 14 — Irrigation Advisor                                       */
/* ------------------------------------------------------------------ */

/**
 * Overall irrigation recommendation for a farm right now. The labels are
 * advisory — they answer "when/how much should I irrigate" using real farm,
 * growth, and (when live) weather data. `insufficient` is an honest state
 * returned when critical context (crop, soil, irrigation method) is missing
 * rather than inventing guidance.
 */
export type IrrigationStatus =
  | "irrigate_now"
  | "irrigation_soon"
  | "delay"
  | "adequate"
  | "insufficient";

/** How much weight should be attached to the recommendation. */
export type IrrigationUrgency = "low" | "medium" | "high";

/**
 * A validated irrigation advisory result (Prompt 14). Produced server-side by
 * the `irrigation-advisor` Edge Function from REAL farm context + growth stage
 * + (when available) live weather. Water amounts are only ever provided with
 * confidence when the available data genuinely supports an estimate; otherwise
 * the system returns relative guidance and says the exact quantity cannot be
 * reliably estimated.
 */
export interface IrrigationRecommendation {
  /** Overall status for the farm right now. */
  status: IrrigationStatus;
  urgency: IrrigationUrgency;
  /** Plain language headline recommendation. */
  recommendation: string;
  /** When to irrigate (timing guidance). */
  timing?: { recommended_time: string; reason: string } | null;
  /**
   * Water quantity guidance. `amount` is null when the exact figure cannot be
   * responsibly estimated from available data. `unit` accompanies amount.
   * `confidence` is 0–100 the model's confidence in the quantity estimate.
   */
  waterGuidance: { amount: string; unit: string; confidence: number; relative: string };
  weatherImpact: string;
  soilImpact: string;
  cropStageImpact: string;
  rainAdjustment: string;
  nextCheck: string;
  importantNotes: string[];
  limitations: string[];
}

/** A persisted irrigation-advisor run. Mirrors an `irrigation_recommendations` row. */
export interface IrrigationRecommendationRecord {
  id: string;
  farmId: string;
  recommendation: IrrigationRecommendation;
  summary: string;
  limitations: string[];
  needsMoreInformation: boolean;
  missingInformation: string[];
  createdAt: string;
}