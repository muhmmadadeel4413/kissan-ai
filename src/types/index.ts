/** Risk categories supported by the Farm Risk Engine (Prompt 8). */
export type RiskType =
  | "disease"
  | "pest"
  | "weather"
  | "irrigation"
  | "crop_stress";

/** How a risk record was produced: deterministic rules and/or AI. */
export type RiskSource = "deterministic" | "ai" | "hybrid";

/** Lifecycle of a persisted risk alert. */
export type RiskStatus = "active" | "expired" | "resolved";

export interface RiskAlert {
  id: string;
  farmId: string;
  riskType: RiskType;
  level: Level;
  title: string;
  explanation: string;
  evidence: string[];
  recommendedActions: string[];
  status: RiskStatus;
  source: RiskSource;
  createdAt: string;
  updatedAt: string;
  expiresAt?: string | null;
}

/** Result of a risk assessment run (used by the UI). */
export interface RiskAssessment {
  risks: RiskAlert[];
  assessedAt: string;
  /** Human-friendly limitations, e.g. weather or diagnoses unavailable. */
  limitations: string[];
}

/** Action categories supported by the Decision Engine (Prompt 10). */
export type ActionCategory =
  | "crop_health"
  | "weather"
  | "irrigation"
  | "pest"
  | "disease"
  | "field_inspection"
  | "growth_stage"
  | "farm_management"
  | "harvest"
  | "monitoring";

/** Timing values the Decision Engine may use (only when context supports it). */
export type ActionTiming =
  | "today"
  | "this_morning"
  | "this_afternoon"
  | "this_evening"
  | "before_rain"
  | "this_week"
  | "monitor";

/** Evidence sources that contributed to an action. */
export type ActionSource =
  | "farm_context"
  | "growth_stage"
  | "weather"
  | "diagnosis"
  | "risk"
  | "yield"
  | "history";

/**
 * A persisted "What should I do today?" action. Mirrors the `action_items`
 * table row. Every field is validated server-side by the Decision Engine —
 * nothing here is ever fabricated client-side.
 */
export interface ActionItem {
  id: string;
  farmId: string;
  /** Date (YYYY-MM-DD) the action applies to. */
  actionDate: string;
  title: string;
  description: string;
  priority: Priority;
  category: ActionCategory;
  reason: string;
  timing: ActionTiming | null;
  source: ActionSource[];
  completed: boolean;
  completedAt: string | null;
  createdAt: string;
}

/** Result of a Decision Engine run (persisted actions + honest context). */
export interface TodayActionsDecision {
  actions: ActionItem[];
  summary: string;
  limitations: string[];
  generatedAt: string;
  actionDate: string;
  /** True when the farm lacks enough info (e.g. no crop) to generate actions. */
  insufficientData: boolean;
}

